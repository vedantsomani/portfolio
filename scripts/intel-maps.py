"""The briefing's satellite zoom (src/components/BriefingIntel.astro): views of the Earth straight down
on Bennett University, Greater Noida, at falling altitudes, every one centred on the same point so
the page can zoom from one into the next.

    python scripts/intel-maps.py

Reads NASA's Blue Marble (blender/assets/earth, from blender/fetch_assets.py) and, when they have
been fetched, Sentinel-2 cloudless tiles (blender/assets/s2/<z>/<x>/<y>.jpg); writes
src/assets/intel/level<N>.jpg (2048 x 2048, orthographic, the target at the centre) and
src/data/intel-levels.json (each level's width in kilometres).
"""

import json
import math
import os

import numpy as np
from PIL import Image, ImageFilter

Image.MAX_IMAGE_PIXELS = None
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EARTH = os.path.join(ROOT, 'blender', 'assets', 'earth', 'blue_marble_21600.jpg')
OUT = os.path.join(ROOT, 'src', 'assets', 'intel')
META = os.path.join(ROOT, 'src', 'data', 'intel-levels.json')
LAT0, LON0 = 28.4507, 77.5820  # Bennett University, Greater Noida
R_KM = 6371.0
SIZE = 2048
# Half the image's width, in Earth radii: the whole globe, then the subcontinent, then the plain.
LEVELS = [1.18, 0.21, 0.045]


def orthographic(src, half, size=SIZE):
    """An orthographic view centred on (LAT0, LON0), half-width `half` Earth radii, sampled
    bilinearly from an equirectangular image. Outside the disk is black."""
    h, w, _ = src.shape
    phi0, lam0 = math.radians(LAT0), math.radians(LON0)
    u = (np.arange(size) + 0.5) / size * 2 - 1
    X, Y = np.meshgrid(u * half, -u * half)
    rho = np.hypot(X, Y)
    inside = rho < 1.0
    c = np.arcsin(np.clip(rho, 0, 1))
    with np.errstate(invalid='ignore', divide='ignore'):
        lat = np.arcsin(np.cos(c) * math.sin(phi0) + np.where(rho > 0, Y * np.sin(c) * math.cos(phi0) / rho, 0))
        lon = lam0 + np.arctan2(X * np.sin(c), rho * np.cos(c) * math.cos(phi0) - Y * np.sin(c) * math.sin(phi0))
    fx = ((np.degrees(lon) + 180) % 360) / 360 * w - 0.5
    fy = (90 - np.degrees(lat)) / 180 * h - 0.5
    x0 = np.floor(fx).astype(int)
    y0 = np.clip(np.floor(fy).astype(int), 0, h - 2)
    ax = (fx - x0)[..., None]
    ay = (fy - y0)[..., None]
    x0 %= w
    x1 = (x0 + 1) % w
    out = (src[y0, x0] * (1 - ax) * (1 - ay) + src[y0, x1] * ax * (1 - ay)
           + src[y0 + 1, x0] * (1 - ax) * ay + src[y0 + 1, x1] * ax * ay)
    out[~inside] = 0
    return out, rho


def atmosphere(img, rho, half):
    """A thin blue limb: the air seen edge-on, brightest just outside the disk."""
    d = rho - 1.0
    glow = np.exp(-np.clip(d, 0, None) / 0.012) * (d > -0.002)
    rim = np.exp(-np.clip(-d, 0, None) / 0.02) * (d <= 0)
    col = np.array([90, 150, 255], dtype=np.float32)
    img = img + (glow[..., None] * 0.9 + rim[..., None] * 0.35) * col
    return np.clip(img, 0, 255)


def main():
    os.makedirs(OUT, exist_ok=True)
    src = np.asarray(Image.open(EARTH).convert('RGB'), dtype=np.float32)
    meta = []
    for i, half in enumerate(LEVELS):
        img, rho = orthographic(src, half)
        if i == 0:
            img = atmosphere(img, rho, half)
        pic = Image.fromarray(img.astype(np.uint8))
        # A satellite feed: a little crisper and colder than the source.
        pic = pic.filter(ImageFilter.UnsharpMask(radius=1.2, percent=60 if i else 30, threshold=2))
        path = os.path.join(OUT, f'level{i}.jpg')
        pic.save(path, quality=88, optimize=True, progressive=True)
        meta.append({'level': i, 'km': round(2 * half * R_KM, 1)})
        print(f'level{i}: {2 * half * R_KM:,.0f} km across -> {os.path.relpath(path, ROOT)}')
    with open(META, 'w', encoding='utf-8') as fh:
        json.dump({'note': 'Generated by scripts/intel-maps.py: the satellite zoom levels, widest first.',
                   'target': [LAT0, LON0], 'levels': meta}, fh, indent=2)
        fh.write('\n')


if __name__ == '__main__':
    main()
